@pytest.mark.parametrize(
    ("topic", "question"),
    [(topic, q) for topic, qs in QUESTIONS.items() for q in qs],
)
def test_dispatcher_question_finds_its_topic(topic: str, question: str) -> None:
    assert topic in detect_topics(question), f"«{question}» → {detect_topics(question)}"


def test_number_of_a_flat_or_a_phone_is_not_a_car_number() -> None:
    """«Номер» сам по себе принадлежал транспорту и перехватывал квартиру и телефон."""
    assert "vehicle" not in detect_topics("Номер квартиры")
    assert "vehicle" not in detect_topics("Номер для обратной связи")
    assert "vehicle" in detect_topics("Номер машины")
